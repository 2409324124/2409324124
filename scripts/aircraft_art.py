def flight_aircraft():
    width, height = 112, 24
    grid = [[' '] * width for _ in range(height)]

    def polygon(points, char):
        for gy in range(height):
            y = 130 + gy * 8
            for gx in range(width):
                x = 10 + gx * 4.7
                inside = False
                j = len(points) - 1
                for i, (xi, yi) in enumerate(points):
                    xj, yj = points[j]
                    if (yi > y) != (yj > y) and x < (xj-xi)*(y-yi)/(yj-yi)+xi:
                        inside = not inside
                    j = i
                if inside:
                    grid[gy][gx] = char

    def ellipse(cx, cy, rx, ry, char):
        for gy in range(height):
            for gx in range(width):
                if ((10+gx*4.7-cx)/rx)**2 + ((130+gy*8-cy)/ry)**2 <= 1:
                    grid[gy][gx] = char

    polygon([(126,164),(257,178),(337,210),(280,225),(180,193)], '▓')
    polygon([(154,168),(260,183),(299,202),(229,191)], '░')
